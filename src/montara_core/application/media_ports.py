"""Port for local original registration, recipes and private execution staging."""
from typing import Protocol

from montara_core.domain.execution import ExecutionSpec, OutputProfile, Shot
from montara_core.domain.jobs import AttemptRef
from montara_core.domain.media import Asset, MediaLocation, RecipeRevision, Representation


class MediaStore(Protocol):
    def register(self, actor: str, project: str, kind: str, locator: str) -> tuple[Asset, Representation, MediaLocation]: ...
    def revise(self, actor: str, asset: str, expected: str, locator: str) -> Representation: ...
    def add_location(self, actor: str, representation: str, locator: str) -> MediaLocation: ...
    def get_representation(self, actor: str, representation: str) -> Representation: ...
    def save_recipe(self, actor: str, project: str, expected: str | None,
                    master: str, shots: tuple[Shot, ...], profile: OutputProfile) -> RecipeRevision: ...
    def get_recipe(self, actor: str, recipe: str) -> RecipeRevision: ...
    def prepare_execution(self, attempt: AttemptRef) -> ExecutionSpec: ...

    def pilot_summary(self, actor: str, project: str) -> dict: ...

    def prepare_fixture(self, actor: str, project: str) -> dict: ...
